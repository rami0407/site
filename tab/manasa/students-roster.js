  function computeExcellenceScore(records) {
    if (!Array.isArray(records) || !records.length) {
      return {
        lessonsCount: 0,
        completedCount: 0,
        totalDurationSec: 0,
        avgChecksPct: 0,
        avgPracticePct: 0,
        avgEvidencePct: 0,
        harvestCount: 0,
        challengePoints: 0,
        overallScore: 0,
        tierLabel: 'لم يشارك بعد',
        tierBadgeBg: '#f1f5f9',
        tierBadgeColor: '#64748b',
        reportCardNote: 'لم يشارك الطالب في حصص منصة مفتاح التفاعلية حتى الآن.'
      };
    }
    var lessonsMap = {};
    records.forEach(function (r) {
      var key = r.sid || r.lessonId || r.title || ('l_' + r.timestamp);
      var prev = lessonsMap[key];
      if (!prev || (r.timestamp || 0) >= (prev.timestamp || 0)) {
        lessonsMap[key] = r;
      }
    });
    var uniqueLessons = Object.keys(lessonsMap).map(function (k) { return lessonsMap[k]; });
    var n = uniqueLessons.length;
    var completed = 0;
    var totalDur = 0;
    var sumChecksPct = 0, cntChecks = 0;
    var sumPracPct = 0, cntPrac = 0;
    var sumEvidPct = 0, cntEvid = 0;
    var harvestCnt = 0;
    var chalPts = 0;
    var sumLessonScores = 0;

    uniqueLessons.forEach(function (r) {
      if (r.done || (r.station && String(r.station).indexOf('✓') >= 0) || r.station === 'ح') completed++;
      totalDur += (Number(r.durationSec) || 0);

      // 1. Station M engagement (15 pts)
      var mScore = 15;

      // 2. Station F checks (25 pts)
      var fPct = 75;
      if (Array.isArray(r.checks) && r.checks[1] > 0) {
        fPct = Math.round((r.checks[0] / r.checks[1]) * 100);
        sumChecksPct += fPct;
        cntChecks++;
      }
      var fScore = (fPct / 100) * 25;

      // 3. Station T practice (25 pts)
      var tPct = 75;
      if (Array.isArray(r.practice) && r.practice[1] > 0) {
        tPct = Math.round((r.practice[0] / r.practice[1]) * 100);
        sumPracPct += tPct;
        cntPrac++;
      }
      var tScore = (tPct / 100) * 25;

      // 4. Station A evidence (25 pts)
      var aPct = 70;
      if (r.evidence && r.evidence.of > 0) {
        aPct = Math.round((r.evidence.score / r.evidence.of) * 100);
        sumEvidPct += aPct;
        cntEvid++;
      } else if (r.result === 'a') {
        aPct = 100; sumEvidPct += 100; cntEvid++;
      } else if (r.result === 'p') {
        aPct = 75; sumEvidPct += 75; cntEvid++;
      } else if (r.result === 'n') {
        aPct = 50; sumEvidPct += 50; cntEvid++;
      }
      var aScore = (aPct / 100) * 25;

      // 5. Station H harvest + Challenge (10 pts)
      var hScore = 5;
      if (r.harvest && Array.isArray(r.harvest) && r.harvest.some(Boolean)) {
        harvestCnt++;
        hScore = 10;
      }
      if (r.challengePoints) {
        chalPts += (Number(r.challengePoints) || 0);
        hScore = 10;
      }

      var lScore = Math.round(mScore + fScore + tScore + aScore + hScore);
      sumLessonScores += Math.min(100, Math.max(50, lScore));
    });

    var avgLessonScore = Math.round(sumLessonScores / n);
    // Participation bonus for active engagement across multiple lessons (up to +6 pts)
    var participationBonus = Math.min(6, (n - 1) * 2);
    var overall = Math.min(100, avgLessonScore + participationBonus);

    var tierLabel = '';
    var tierBg = '';
    var tierColor = '';
    var note = '';

    if (overall >= 90) {
      tierLabel = '🌟 تميّز فائق (A+)';
      tierBg = '#dcfce7';
      tierColor = '#15803d';
      note = 'يُظهر تميّزاً فائقاً ومبادرةً عالية في التعلّم الذاتي والتعاوني عبر منصة مفتاح، ويتقن بناء المعنى وإثبات الدليل بتفوّق.';
    } else if (overall >= 80) {
      tierLabel = '⭐ تميّز متقدّم (A)';
      tierBg = '#e0f2fe';
      tierColor = '#0369a1';
      note = 'يُظهر تفاعلاً متميّزاً وفهماً متقناً في محطات التعلّم والتدريب التعاوني عبر منصة مفتاح، ويتقدّم بثبات وإيجابية.';
    } else if (overall >= 70) {
      tierLabel = '👍 تميّز صاعد (B)';
      tierBg = '#fef3c7';
      tierColor = '#92400e';
      note = 'يُشارك بفاعلية في أنشطة منصة مفتاح التفاعلية ويُظهر تحسّناً مستمرّاً في التدريب وإثبات الفهم.';
    } else {
      tierLabel = '🌱 في طور التمكّن (C)';
      tierBg = '#ffedd5';
      tierColor = '#c2410c';
      note = 'يُشارك في محطات منصة مفتاح ويواظب على التدرّب لتعزيز الفهم وإتقان المهارات المطلوبة.';
    }

    return {
      lessonsCount: n,
      completedCount: completed,
      totalDurationSec: totalDur,
      avgChecksPct: cntChecks ? Math.round(sumChecksPct / cntChecks) : 0,
      avgPracticePct: cntPrac ? Math.round(sumPracPct / cntPrac) : 0,
      avgEvidencePct: cntEvid ? Math.round(sumEvidPct / cntEvid) : 0,
      harvestCount: harvestCnt,
      challengePoints: chalPts,
      overallScore: overall,
      tierLabel: tierLabel,
      tierBadgeBg: tierBg,
      tierBadgeColor: tierColor,
      reportCardNote: note,
      lessonsList: uniqueLessons
    };
  }

